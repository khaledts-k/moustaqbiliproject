"""
Builds assets/js/nbaq-uk-data.js from the NBAQ "recommended universities" search
(https://nbaq.edu.kw/search/): for each UK major in the Ministry's plan (plan-majors-data.js),
the UK universities NBAQ approves for it.

Run from the project folder:  python scripts/fetch_nbaq_uk.py
Re-run whenever NBAQ updates its lists, then check the Scholarships page.
"""
import datetime
import json
import pathlib
import urllib.parse
import urllib.request

API = "https://search.nbaq.edu.kw/nbaq/search/api/majors-data"
OUT = pathlib.Path(__file__).resolve().parent.parent / "assets" / "js" / "nbaq-uk-data.js"

# Plan major id (plan-majors-data.js) -> NBAQ subject names that cover it.
# "unconfirmed": NBAQ has no subject with this exact name; we use the closest NBAQ subject
# and the site shows a "Not confirmed" label. Majors left out here show a link to the NBAQ search.
MAJORS = {
    "medicine": {"nbaq": ["Medicine"]},
    "dentistry": {"nbaq": ["Dentistry"]},
    "nursing": {"nbaq": ["Nursing"]},
    "physiotherapy": {"nbaq": ["Physiotherapy"]},
    "radiography": {"nbaq": ["Medical Technology"], "unconfirmed": True},
    "pharmacology": {"nbaq": ["Pharmacology & Pharmacy", "Pharmacology and Pharmacy"]},
    "nutrition": {"nbaq": ["Nutrition"]},
    "computer-science": {"nbaq": ["Computer Science"]},
    "computer-science-cyber-security": {"nbaq": ["Computer Science"], "unconfirmed": True},
    "computer-science-ai": {"nbaq": ["Computer Science"], "unconfirmed": True},
    "data-science": {"nbaq": ["Computer Science"], "unconfirmed": True},
    "food-science": {"nbaq": ["Food Science"]},
}


def fetch_all(country):
    rows, page, total_pages = [], 1, 1
    while page <= total_pages:
        query = urllib.parse.urlencode({"lang": "en", "country": country, "page": page, "perPage": 100})
        with urllib.request.urlopen(f"{API}?{query}", timeout=60) as resp:
            data = json.load(resp)
        rows += data.get("data") or []
        total_pages = data.get("totalPages", 1)
        page += 1
    return rows


def clean(s):
    return " ".join((s or "").split())


def uni_name(name):
    # "University of Edinburgh, The" -> "University of Edinburgh"
    # "Imperial College of ... (Also Known as Imperial College London)" -> "Imperial College London"
    name = clean(name).replace("’", "'")
    if "(Also Known as " in name:
        name = name.split("(Also Known as ", 1)[1].rstrip(")")
    return name[:-5] if name.endswith(", The") else name


def main():
    rows = fetch_all("United Kingdom")
    out = {}
    for major_id, cfg in MAJORS.items():
        unis = {}
        for r in rows:
            if clean(r.get("major_en") or r.get("major")) not in cfg["nbaq"]:
                continue
            name = uni_name(r["university"])
            levels = {k for k in ("bachelor", "master", "phd") if r.get(k) == "yes"}
            prev = unis.get(name, (set(), 0))
            unis[name] = (prev[0] | levels, max(prev[1], 1 if r.get("merit_major") else 0))
        # A university whose levels are all "stopped" is suspended for Kuwaiti students: leave it out
        unis = {n: v for n, v in unis.items() if v[0]}
        if not unis:
            raise SystemExit(f"No NBAQ rows for {major_id}: {cfg['nbaq']}")
        rows_out = sorted(
            ([n, "".join(k[0].upper() for k in ("bachelor", "master", "phd") if k in lv), m] for n, (lv, m) in unis.items()),
            key=lambda u: (-u[2], u[0]),
        )
        out[major_id] = {"nbaq": cfg["nbaq"], "unconfirmed": cfg.get("unconfirmed", False), "unis": rows_out}

    today = datetime.date.today().isoformat()
    body = ",\n".join(
        f"  {json.dumps(mid)}: {{\n    nbaq: {json.dumps(m['nbaq'])},\n    unconfirmed: {'true' if m['unconfirmed'] else 'false'},\n    unis: [\n"
        + ",\n".join("      " + json.dumps(u, ensure_ascii=False) for u in m["unis"])
        + "\n    ]\n  }"
        for mid, m in out.items()
    )
    OUT.write_text(f"""/**
 * moustaqbili | مستقبلي
 * UK universities approved by NBAQ (National Bureau for Academic Accreditation) for each UK major
 * in the Ministry's plan. Generated by scripts/fetch_nbaq_uk.py on {today}. Do not edit by hand.
 *
 * Sources:
 * 1. NBAQ recommended-universities search: https://nbaq.edu.kw/search/
 * 2. UK merit list, Ministerial Decree 16/2025 (16 January 2025): https://nbaq.edu.kw/website/merits
 *
 * Keys are plan major ids (plan-majors-data.js).
 * nbaq: the NBAQ subject(s) used. unconfirmed: NBAQ has no subject with the plan's exact name.
 * unis: [university, degree levels (B = Bachelor, M = Master, P = PhD), on merit list (1/0)], merit first.
 */

const NBAQ_UK_CHECKED = "{today}";

const NBAQ_UK = {{
{body}
}};

if (typeof window !== 'undefined') {{
  window.NBAQ_UK = NBAQ_UK;
  window.NBAQ_UK_CHECKED = NBAQ_UK_CHECKED;
}}
""", encoding="utf-8", newline="\n")
    print(f"Wrote {OUT}")
    for mid, m in out.items():
        print(f"  {mid}: {len(m['unis'])} universities, {sum(u[2] for u in m['unis'])} merit")


if __name__ == "__main__":
    main()
